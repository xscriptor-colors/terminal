BLOCK
)"

build_block() {
  local export_line="$1" dir_export="$2" rc_export="$3" init_line="$4" line
  while IFS= read -r line; do
    case "$line" in
      '__XSC_EXPORT_LINE__') [[ -n "$export_line" ]] && printf '%s\n' "$export_line" ;;
      '__XSC_DIR_EXPORT__') [[ -n "$dir_export" ]] && printf '%s\n' "$dir_export" ;;
      '__XSC_RC_EXPORT__') [[ -n "$rc_export" ]] && printf '%s\n' "$rc_export" ;;
      '__XSC_INIT_LINE__') [[ -n "$init_line" ]] && printf '%s\n' "$init_line" ;;
      *) printf '%s\n' "${line//__XSC_DEFAULT_THEME__/$THEME}" ;;
    esac
  done <<< "$BLOCK_TEMPLATE"
}

compute_export_line() {
  local base="$1" active_managed="$2" export_line
  if [[ "$active_managed" == 1 ]]; then
    export_line="export STARSHIP_CONFIG=$(path_expr "$ACTIVE_FILE")"
  elif has_export_line "$base"; then
    export_line=""
  else
    export_line="export STARSHIP_CONFIG=$(path_expr "$DEST_DIR/themes/$THEME.toml")"
  fi
  printf '%s\n' "$export_line"
}

compute_dir_export() {
  if [[ "$DEST_DIR" != "$AUTO_DEST_DIR" ]]; then
    printf 'export XSC_STARSHIP_DIR=%s\n' "$(path_expr "$DEST_DIR")"
  fi
}

compute_rc_export() {
  if [[ -n "$CONFIG_FILE" && "$CONFIG_FILE" != "$AUTO_RC" ]]; then
    printf 'export XSC_STARSHIP_SHELL_RC=%s\n' "$(path_expr "$CONFIG_FILE")"
  fi
}

compute_init_line() {
  local base="$1" shell_name line=""
  shell_name="$(rc_shell)"
  if [[ "$NO_INIT" == 0 && ( "$shell_name" == "zsh" || "$shell_name" == "bash" ) ]]; then
    if ! has_init_line "$base"; then
      line="command -v starship >/dev/null 2>&1 && eval \"\$(starship init $shell_name)\""
    fi
  fi
  printf '%s\n' "$line"
}

active_is_managed() {
  [[ ! -e "$ACTIVE_FILE" ]] || is_managed_file "$ACTIVE_FILE"
}

write_active_config() {
  local theme_path="$DEST_DIR/themes/$THEME.toml" real marker tmp
  [[ -f "$theme_path" ]] || { echo "Error: theme not found: $theme_path" >&2; exit 1; }
  mkdir -p "$(dirname "$ACTIVE_FILE")"
  real="$(resolve_path "$ACTIVE_FILE")"
  mkdir -p "$(dirname "$real")"
  marker="$(marker_to_write "$ACTIVE_FILE")"
  tmp="$(mktemp "${real}.xsc.XXXXXX")"
  { printf '%s\n' "$marker"; cat "$theme_path"; } > "$tmp"
  cat "$tmp" > "$real"
  rm -f "$tmp"
  echo "Active config: $ACTIVE_FILE (theme: $THEME)"
}

install_rc_block() {
  local real base export_line dir_export rc_export init_line block tmp
  mkdir -p "$(dirname "$CONFIG_FILE")"
  real="$(resolve_path "$CONFIG_FILE")"
  base="$(prepare_base "$real")"
  export_line="$(compute_export_line "$base" "$1")"
  dir_export="$(compute_dir_export)"
  rc_export="$(compute_rc_export)"
  init_line="$(compute_init_line "$base")"
  block="$(build_block "$export_line" "$dir_export" "$rc_export" "$init_line")"
  tmp="$(mktemp)"
  { cat "$base"; printf '%s\n' "$block"; } > "$tmp"
  backup_rc "$real"
  write_through_link "$tmp" "$real"
  rm -f "$tmp" "$base"
  echo "Updated shell config: $CONFIG_FILE"
}

uninstall_starship() {
  local real base dest="$DEST_DIR" parsed=""
  if [[ -z "${XSC_STARSHIP_DIR:-}" && -n "$CONFIG_FILE" && -f "$CONFIG_FILE" ]]; then
    parsed="$(read_export_value "$CONFIG_FILE" XSC_STARSHIP_DIR || true)"
    if [[ -n "$parsed" ]]; then
      dest="$parsed"
    fi
  fi
  if [[ -n "$CONFIG_FILE" && -d "$(dirname "$CONFIG_FILE")" && -f "$CONFIG_FILE" ]]; then
    real="$(resolve_path "$CONFIG_FILE")"
    base="$(prepare_base "$real")"
    backup_rc "$real"
    write_through_link "$base" "$real"
    rm -f "$base"
    echo "Removed managed block: $CONFIG_FILE"
  fi
  if [[ -f "$ACTIVE_FILE" ]] && is_managed_file "$ACTIVE_FILE"; then
    if grep -qF "$MARKER_LEGACY" "$ACTIVE_FILE" 2>/dev/null &&
       [[ ! -d "$CONFIG_HOME/equisdots/starship" ]]; then
      rm -f "$ACTIVE_FILE"
      echo "Removed: $ACTIVE_FILE"
    else
      echo "Kept: $ACTIVE_FILE (managed by theme-sync)"
    fi
  fi
  if [[ -d "$CONFIG_HOME/xscriptor/starship" ]]; then
    rm -rf "$CONFIG_HOME/xscriptor/starship"
    echo "Removed: $CONFIG_HOME/xscriptor/starship"
  fi
  if [[ -d "$CONFIG_HOME/equisdots/starship" ]]; then
    echo "Kept: $CONFIG_HOME/equisdots/starship (owned by equisdots)"
  fi
  if [[ "$dest" != "/" && -n "$dest" &&
        "$dest" != "$CONFIG_HOME/xscriptor/starship" &&
        "$dest" != "$CONFIG_HOME/equisdots/starship" &&
        -d "$dest" ]]; then
    rm -rf "$dest"
    echo "Removed: $dest"
  fi
}

SOURCE_DIR=""
resolve_source() {
  local self="${BASH_SOURCE[0]:-}" source_dir repo_dir
  if [[ -n "${XSC_STARSHIP_SOURCE_DIR:-}" ]]; then
    SOURCE_DIR="$XSC_STARSHIP_SOURCE_DIR"
    return 0
  fi
  if [[ -n "$self" && "$self" != "bash" && "$self" != "-" ]]; then
    source_dir="$(cd "$(dirname "$self")" && pwd)"
    if [[ -f "$source_dir/starship.toml" && -d "$source_dir/themes" ]]; then
      SOURCE_DIR="$source_dir"
      return 0
    fi
  fi
  TMP_DIR="$(mktemp -d)"
  echo "Downloading Starship prompts (ref: $REF)..."
  if command -v curl >/dev/null 2>&1; then
    curl -fsSL "$REPO_URL/archive/refs/heads/$REF.tar.gz" | tar -xz -C "$TMP_DIR"
  elif command -v wget >/dev/null 2>&1; then
    wget -qO- "$REPO_URL/archive/refs/heads/$REF.tar.gz" | tar -xz -C "$TMP_DIR"
  else
    echo "Error: curl or wget is required." >&2
    exit 1
  fi
  repo_dir="$(find "$TMP_DIR" -maxdepth 1 -type d -name 'terminal-*' -print -quit)"
  if [[ -z "$repo_dir" || ! -d "$repo_dir/prompts/starship" ]]; then
    echo "Error: prompts/starship not found in archive." >&2
    exit 1
  fi
  SOURCE_DIR="$repo_dir/prompts/starship"
}

run_theme_sync() {
  local ts=""
  if [[ -x "$HOME_DIR/.local/share/equisdots/theme-sync/theme-sync.sh" ]]; then
    ts="$HOME_DIR/.local/share/equisdots/theme-sync/theme-sync.sh"
  elif command -v theme-sync.sh >/dev/null 2>&1; then
    ts="$(command -v theme-sync.sh)"
  fi
  if [[ -z "$ts" ]]; then
    echo "Note: theme-sync not found; skipping --sync." >&2
    return 0
  fi
  if ! "$ts" --targets starship; then
    echo "Warning: theme-sync failed; the installed files were kept." >&2
  fi
}

if [[ "$DO_UNINSTALL" == 1 ]]; then
  uninstall_starship
  exit 0
fi

if [[ "$PRINT_ONLY" == 1 ]]; then
  if [[ -n "$CONFIG_FILE" && -d "$(dirname "$CONFIG_FILE")" && -f "$CONFIG_FILE" ]]; then
    real_rc="$(resolve_path "$CONFIG_FILE")"
    base="$(prepare_base "$real_rc")"
  else
    base="$(mktemp)"
    : > "$base"
  fi
  active_managed=0
  if active_is_managed; then
    active_managed=1
  fi
  block="$(build_block \
    "$(compute_export_line "$base" "$active_managed")" \
    "$(compute_dir_export)" \
    "$(compute_rc_export)" \
    "$(compute_init_line "$base")")"
  printf '%s\n' "$block"
  rm -f "$base"
  exit 0
fi

if [[ "$DEST_DIR" == "/" || -z "$DEST_DIR" ]]; then
  echo "Error: invalid install directory." >&2
  exit 1
fi

resolve_source
if [[ ! -f "$SOURCE_DIR/themes/$THEME.toml" ]]; then
  echo "Error: theme not found in source: $THEME" >&2
  exit 1
fi

if [[ "$(resolve_path "$SOURCE_DIR")" != "$(resolve_path "$DEST_DIR")" ]]; then
  mkdir -p "$DEST_DIR/themes"
  for f in install.sh README.md starship.toml; do
    if [[ -f "$SOURCE_DIR/$f" ]]; then
      cp -a "$SOURCE_DIR/$f" "$DEST_DIR/$f"
    fi
  done
  if [[ -d "$SOURCE_DIR/themes" ]]; then
    cp -a "$SOURCE_DIR"/themes/. "$DEST_DIR/themes/"
  fi
fi

echo "Installed Starship themes to: $DEST_DIR"

active_managed=0
if active_is_managed; then
  active_managed=1
  write_active_config
else
  echo "Kept user config: $ACTIVE_FILE (not generated by theme-sync)"
fi

if [[ -n "$CONFIG_FILE" ]]; then
  install_rc_block "$active_managed"
else
  echo "Note: shell config not detected. Set XSC_STARSHIP_SHELL_RC and re-run." >&2
fi

if ! command -v starship >/dev/null 2>&1; then
