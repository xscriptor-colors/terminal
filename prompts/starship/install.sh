#!/usr/bin/env bash
set -euo pipefail

REPO_URL="https://github.com/xscriptor-colors/terminal"
REF="${XSC_STARSHIP_REF:-main}"

HOME_DIR="${HOME:-}"
if [[ -z "$HOME_DIR" ]]; then
  echo "Error: HOME is not set." >&2
  exit 1
fi
CONFIG_HOME="$HOME_DIR/.config"
ACTIVE_FILE="$CONFIG_HOME/starship.toml"

MARKER_EQUISDOTS="# Auto-generated by theme-sync.sh (equisdots). Do not edit."
MARKER_LEGACY="# Auto-generated by theme-sync.sh (xscriptor-colors). Do not edit."

START_MARKER="# >>> xscriptor-starship >>>"
END_MARKER="# <<< xscriptor-starship <<<"
OLD_BLOCKS_START=("# xscriptor-starship-v2" "# xscriptor-starship-aliases")
OLD_BLOCKS_END=("# xscriptor-starship-v2-end" "# xscriptor-starship-aliases-end")

THEME="${XSC_STARSHIP_THEME:-x}"
DO_UNINSTALL=0
PRINT_ONLY=0
RUN_SYNC=0
NO_INIT=0

TMP_DIR=""
cleanup() {
  if [[ -n "${TMP_DIR:-}" ]]; then
    rm -rf "$TMP_DIR"
  fi
}
trap cleanup EXIT

usage() {
  cat <<'EOF'
Usage: install.sh [options]

Options:
  --theme NAME     Theme to install (default: x)
  --uninstall, -u  Remove the managed block and generated files
  --print          Print the managed .zshrc/.bashrc block and exit
  --sync           Run equisdots theme-sync (starship target) after install
  --no-init        Do not add `starship init` to the shell config
  -h, --help       Show this help

Environment:
  XSC_STARSHIP_DIR        Theme root (default: ~/.config/equisdots/starship
                          when equisdots is present, else ~/.config/xscriptor/starship)
  XSC_STARSHIP_SHELL_RC   Shell config file (default: ~/.zshrc or ~/.bashrc)
  XSC_STARSHIP_REF        Git ref to download (default: main)
  XSC_STARSHIP_THEME      Default theme (same as --theme)
  XSC_STARSHIP_SOURCE_DIR Local prompts/starship directory (skip download)
EOF
}

while (($# > 0)); do
  case "$1" in
    --theme)
      [[ $# -ge 2 ]] || { echo "Error: --theme requires a value." >&2; exit 2; }
      THEME="$2"
      shift 2
      ;;
    --theme=*)
      THEME="${1#*=}"
      shift
      ;;
    --uninstall|-u|uninstall)
      DO_UNINSTALL=1
      shift
      ;;
    --print)
      PRINT_ONLY=1
      shift
      ;;
    --sync)
      RUN_SYNC=1
      shift
      ;;
    --no-init)
      NO_INIT=1
      shift
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      echo "Error: unknown option: $1" >&2
      usage >&2
      exit 2
      ;;
  esac
done

if [[ ! "$THEME" =~ ^[A-Za-z0-9._-]+$ ]]; then
  echo "Error: invalid theme name: $THEME" >&2
  exit 1
fi

resolve_path() {
  local p="$1" d
  while [[ -L "$p" ]]; do
    d="$(cd "$(dirname "$p")" && pwd -P)" || return 1
    p="$(readlink "$p")" || return 1
    [[ "$p" == /* ]] || p="$d/$p"
  done
  if [[ -d "$(dirname "$p")" ]]; then
    d="$(cd "$(dirname "$p")" && pwd -P)" || return 1
    printf '%s/%s\n' "$d" "$(basename "$p")"
  else
    printf '%s\n' "$p"
  fi
}

dq() {
  local s="$1"
  s="${s//\\/\\\\}"
  s="${s//\"/\\\"}"
  s="${s//\$/\\\$}"
  s="${s//\`/\\\`}"
  printf '"%s"' "$s"
}

path_expr() {
  local p="$1"
  case "$p" in
    "$HOME_DIR"/.config/*)
      printf '"$HOME/.config/%s"' "${p#"$HOME_DIR"/.config/}"
      ;;
    *)
      dq "$p"
      ;;
  esac
}

detect_auto_rc() {
  case "$(basename "${SHELL:-}")" in
    zsh) printf '%s\n' "${ZDOTDIR:-$HOME_DIR}/.zshrc" ;;
    bash) printf '%s\n' "$HOME_DIR/.bashrc" ;;
    *) printf '\n' ;;
  esac
}

if [[ -d "$CONFIG_HOME/equisdots/starship" ]]; then
  AUTO_DEST_DIR="$CONFIG_HOME/equisdots/starship"
else
  AUTO_DEST_DIR="$CONFIG_HOME/xscriptor/starship"
fi
DEST_DIR="${XSC_STARSHIP_DIR:-$AUTO_DEST_DIR}"

AUTO_RC="$(detect_auto_rc)"
CONFIG_FILE="${XSC_STARSHIP_SHELL_RC:-$AUTO_RC}"

rc_shell() {
  [[ -n "$CONFIG_FILE" ]] || return 0
  case "$(basename "$CONFIG_FILE")" in
    .zshrc|*zsh*) printf 'zsh\n' ;;
    .bashrc|*bash*) printf 'bash\n' ;;
    *) basename "${SHELL:-}" ;;
  esac
}

is_managed_file() {
  local f="$1"
  [[ -f "$f" ]] || return 1
  grep -qF "$MARKER_EQUISDOTS" "$f" 2>/dev/null ||
    grep -qF "$MARKER_LEGACY" "$f" 2>/dev/null
}

marker_to_write() {
  local f="$1" first=""
  if [[ -f "$f" ]]; then
    IFS= read -r first < "$f" || true
  fi
  if [[ "$first" == "$MARKER_EQUISDOTS" || "$first" == "$MARKER_LEGACY" ]]; then
    printf '%s\n' "$first"
  elif [[ "$DEST_DIR" == "$CONFIG_HOME/equisdots/starship" ]]; then
    printf '%s\n' "$MARKER_EQUISDOTS"
  else
    printf '%s\n' "$MARKER_LEGACY"
  fi
}

strip_closed_range() {
  awk -v s="$2" -v e="$3" '
    { line[NR] = $0 }
    END {
      start = 0
      stop = 0
      for (i = 1; i <= NR; i++) {
        if (line[i] == s) { start = i; break }
      }
      if (start) {
        for (j = start + 1; j <= NR; j++) {
          if (line[j] == e) { stop = j; break }
        }
      }
      for (i = 1; i <= NR; i++) {
        if (start && stop && i >= start && i <= stop) continue
        print line[i]
      }
    }
  ' "$1"
}

strip_all_closed() {
  local file="$1" start="$2" end="$3" changed=1 tmp
  while [[ "$changed" == 1 ]]; do
    changed=0
    tmp="$(mktemp)"
    strip_closed_range "$file" "$start" "$end" > "$tmp"
    if ! cmp -s "$file" "$tmp"; then
      changed=1
    fi
    mv "$tmp" "$file"
  done
}

remove_managed_exports() {
  awk '
    /^export STARSHIP_CONFIG=/ {
      if (index($0, "/xscriptor/starship/themes/") ||
          index($0, "/equisdots/starship/themes/")) next
    }
    { print }
  ' "$1"
}

prepare_base() {
  local src="$1" base tmp s e i
  base="$(mktemp)"
  if [[ -f "$src" ]]; then
    cp -a "$src" "$base"
  else
    : > "$base"
  fi
  for i in "${!OLD_BLOCKS_START[@]}"; do
    s="${OLD_BLOCKS_START[$i]}"
    e="${OLD_BLOCKS_END[$i]}"
    strip_all_closed "$base" "$s" "$e"
  done
  strip_all_closed "$base" "$START_MARKER" "$END_MARKER"
  tmp="$(mktemp)"
  remove_managed_exports "$base" > "$tmp"
  mv "$tmp" "$base"
  printf '%s\n' "$base"
}

has_export_line() {
  grep -q '^export STARSHIP_CONFIG=' "$1" 2>/dev/null
}

read_export_value() {
  local file="$1" name="$2" line val
  line="$(grep -m1 "^export $name=" "$file" 2>/dev/null || true)"
  [[ -n "$line" ]] || return 1
  val="${line#*=}"
  case "$val" in
    \"*\") val="${val#\"}"; val="${val%\"}" ;;
  esac
  case "$val" in
    '$HOME'/*) val="$HOME_DIR/${val#\$HOME/}" ;;
    '${HOME}'/*) val="$HOME_DIR/${val#\$\{HOME\}/}" ;;
  esac
  printf '%s\n' "$val"
}

has_init_line() {
  awk '
    /^[[:space:]]*#/ { next }
    /starship init (zsh|bash)/ { found = 1 }
    END { exit(found ? 0 : 1) }
  ' "$1" 2>/dev/null
}

backup_rc() {
  local real="$1" bak="$1.xscriptor-starship.bak"
  if [[ -f "$real" && ! -e "$bak" ]]; then
    cp -a "$real" "$bak" 2>/dev/null || true
  fi
}

write_through_link() {
  local src="$1" dst="$2" real tmp
  real="$(resolve_path "$dst")" || return 1
  mkdir -p "$(dirname "$real")" || return 1
  tmp="$(mktemp "${real}.xsc.XXXXXX")" || return 1
  cp -a "$src" "$tmp" || { rm -f "$tmp"; return 1; }
  cat "$tmp" > "$real" && rm -f "$tmp"
}

BLOCK_TEMPLATE="$(cat <<'BLOCK'
# >>> xscriptor-starship >>>
# Managed by xscriptor-colors/terminal. Compatible with equisdots theme-sync.
# Remove this block (or run install.sh --uninstall) to undo.
__XSC_EXPORT_LINE__
__XSC_DIR_EXPORT__
__XSC_RC_EXPORT__

xscriptor_starship_realpath() {
  local p="$1" d
  while [[ -L "$p" ]]; do
    d="$(cd "$(dirname "$p")" && pwd -P)" || return 1
    p="$(readlink "$p")" || return 1
    [[ "$p" == /* ]] || p="$d/$p"
  done
  d="$(cd "$(dirname "$p")" && pwd -P)" || return 1
  printf "%s/%s\n" "$d" "$(basename "$p")"
}

xscriptor_starship_dq() {
  local s="$1"
  s="${s//\\/\\\\}"
  s="${s//\"/\\\"}"
  s="${s//\$/\\\$}"
  s="${s//\`/\\\`}"
  printf "\"%s\"" "$s"
}

xscriptor_starship_dir() {
  if [[ -n "${XSC_STARSHIP_DIR:-}" ]]; then
    printf "%s\n" "$XSC_STARSHIP_DIR"
  elif [[ -d "$HOME/.config/equisdots/starship" ]]; then
    printf "%s\n" "$HOME/.config/equisdots/starship"
  else
    printf "%s\n" "$HOME/.config/xscriptor/starship"
  fi
}

xscriptor_starship_rc() {
  if [[ -n "${XSC_STARSHIP_SHELL_RC:-}" ]]; then
    printf "%s\n" "$XSC_STARSHIP_SHELL_RC"
    return 0
  fi
  case "$(basename "${SHELL:-}")" in
    zsh) printf "%s\n" "${ZDOTDIR:-$HOME}/.zshrc" ;;
    bash) printf "%s\n" "$HOME/.bashrc" ;;
    *) printf "\n" ;;
  esac
}

xscriptor_starship_is_managed() {
  local f="$1"
  [[ -f "$f" ]] || return 1
  grep -qF "# Auto-generated by theme-sync.sh (equisdots). Do not edit." "$f" 2>/dev/null ||
    grep -qF "# Auto-generated by theme-sync.sh (xscriptor-colors). Do not edit." "$f" 2>/dev/null
}

xscriptor_starship_marker() {
  local f="$1" first=""
  if [[ -f "$f" ]]; then
    IFS= read -r first < "$f" || true
  fi
  if [[ "$first" == "# Auto-generated by theme-sync.sh (equisdots). Do not edit." ||
        "$first" == "# Auto-generated by theme-sync.sh (xscriptor-colors). Do not edit." ]]; then
    printf "%s\n" "$first"
  elif [[ -d "$HOME/.config/equisdots/starship" ]]; then
    printf "%s\n" "# Auto-generated by theme-sync.sh (equisdots). Do not edit."
  else
    printf "%s\n" "# Auto-generated by theme-sync.sh (xscriptor-colors). Do not edit."
  fi
}

xscriptor_starship_write_active() {
  local theme_path="$1"
  local active="$HOME/.config/starship.toml"
  local real marker tmp
  [[ -f "$theme_path" ]] || { printf "Theme not found: %s\n" "$theme_path" >&2; return 1; }
  mkdir -p "$(dirname "$active")" || return 1
  real="$(xscriptor_starship_realpath "$active")" || return 1
  mkdir -p "$(dirname "$real")" || return 1
  marker="$(xscriptor_starship_marker "$active")"
  tmp="$(mktemp "${real}.xsc.XXXXXX")" || return 1
  { printf "%s\n" "$marker"; cat "$theme_path"; } > "$tmp" || { rm -f "$tmp"; return 1; }
  cat "$tmp" > "$real" && rm -f "$tmp"
}

xscriptor_starship_set_export() {
  local target="$1" rc real tmp line
  rc="$(xscriptor_starship_rc)"
  [[ -n "$rc" && -f "$rc" ]] || return 0
  real="$(xscriptor_starship_realpath "$rc")" || return 1
  line="export STARSHIP_CONFIG=$(xscriptor_starship_dq "$target")"
  tmp="$(mktemp "${real}.xsc.XXXXXX")" || return 1
  XSC_LINE="$line" awk '
    /^export STARSHIP_CONFIG=/ { if (!done) { print ENVIRON["XSC_LINE"]; done=1 } next }
    $0 == "# <<< xscriptor-starship <<<" { if (!done) { print ENVIRON["XSC_LINE"]; done=1 } }
    { print }
    END { if (!done) print ENVIRON["XSC_LINE"] }
  ' "$real" > "$tmp"
  cat "$tmp" > "$real" && rm -f "$tmp"
}

xscriptor_starship_apply() {
  local theme_path="$1"
  local active="$HOME/.config/starship.toml"
  [[ -f "$theme_path" ]] || { printf "Theme not found: %s\n" "$theme_path" >&2; return 1; }
  if [[ ! -e "$active" ]] || xscriptor_starship_is_managed "$active"; then
    xscriptor_starship_write_active "$theme_path" || return 1
    export STARSHIP_CONFIG="$active"
  else
    export STARSHIP_CONFIG="$theme_path"
    xscriptor_starship_set_export "$theme_path" || return 1
  fi
  printf "Starship theme: %s\n" "$theme_path"
}

xscriptor_starship_set() {
  xscriptor_starship_apply "$1"
}

xscriptor_starship_theme() {
  local name="${1:-__XSC_DEFAULT_THEME__}"
  xscriptor_starship_apply "$(xscriptor_starship_dir)/themes/$name.toml"
}

xscriptor_starship_base() {
  xscriptor_starship_apply "$(xscriptor_starship_dir)/starship.toml"
}

